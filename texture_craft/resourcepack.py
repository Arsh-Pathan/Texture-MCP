"""Minecraft resource pack manager and CustomModelData coordinator."""

import json
import pathlib
import re
from typing import Dict, Any, Optional, List
from PIL import Image

# Minecraft pack_format mapping
# 1.20.2 = 18, 1.20.4 = 22, 1.20.5-1.20.6 = 32, 1.21-1.21.1 = 34, 1.21.2-1.21.3 = 42, 1.21.4 = 46
DEFAULT_PACK_FORMAT = 34


def sanitize_id(raw: str) -> str:
    """Sanitizes names into valid lowercase Minecraft ResourceLocation path."""
    clean = re.sub(r"[^a-z0-9_.-]", "_", raw.lower().strip())
    clean = re.sub(r"_+", "_", clean).strip("_")
    return clean or "item"


class ResourcePackManager:
    def __init__(self, pack_dir: str | pathlib.Path):
        self.pack_dir = pathlib.Path(pack_dir)

    def init_pack(
        self,
        pack_name: str = "TextureCraft_Pack",
        description: str = "Custom Textures generated by Texture-Craft",
        pack_format: int = DEFAULT_PACK_FORMAT,
    ) -> Dict[str, Any]:
        """Initializes standard resource pack layout and pack.mcmeta."""
        self.pack_dir.mkdir(parents=True, exist_ok=True)
        mcmeta_path = self.pack_dir / "pack.mcmeta"

        mcmeta = {
            "pack": {
                "pack_format": int(pack_format),
                "description": description,
            }
        }
        mcmeta_path.write_text(json.dumps(mcmeta, indent=2), encoding="utf-8")

        # Create standard Minecraft directory skeleton
        (self.pack_dir / "assets" / "minecraft" / "models" / "item").mkdir(parents=True, exist_ok=True)

        return {
            "pack_dir": str(self.pack_dir),
            "pack_name": pack_name,
            "mcmeta_path": str(mcmeta_path),
            "pack_format": pack_format,
        }

    def save_texture(
        self,
        namespace: str,
        item_id: str,
        image: Image.Image,
    ) -> pathlib.Path:
        """Saves 16x16 RGBA image to assets/<namespace>/textures/item/<item_id>.png."""
        ns = sanitize_id(namespace)
        item = sanitize_id(item_id)
        tex_dir = self.pack_dir / "assets" / ns / "textures" / "item"
        tex_dir.mkdir(parents=True, exist_ok=True)

        target_file = tex_dir / f"{item}.png"
        image.save(target_file, format="PNG")
        return target_file

    def create_item_model(
        self,
        namespace: str,
        item_id: str,
        is_handheld: bool = False,
    ) -> pathlib.Path:
        """Creates assets/<namespace>/models/item/<item_id>.json."""
        ns = sanitize_id(namespace)
        item = sanitize_id(item_id)
        model_dir = self.pack_dir / "assets" / ns / "models" / "item"
        model_dir.mkdir(parents=True, exist_ok=True)

        parent = "minecraft:item/handheld" if is_handheld else "minecraft:item/generated"
        model_data = {
            "parent": parent,
            "textures": {
                "layer0": f"{ns}:item/{item}"
            }
        }

        target_file = model_dir / f"{item}.json"
        target_file.write_text(json.dumps(model_data, indent=2), encoding="utf-8")
        return target_file

    def register_custom_model_data(
        self,
        base_item: str,
        custom_model_data: int,
        target_model: str,
    ) -> pathlib.Path:
        """Registers a CustomModelData model for the target resource pack format.

        Before pack format 46, item models use ``overrides`` in
        ``assets/minecraft/models/item``. In format 46 (Minecraft 1.21.4) and
        later, item models are selected through client item definitions under
        ``assets/minecraft/items``; the old hardcoded model paths and
        ``overrides`` are no longer read.
        """
        base = sanitize_id(base_item)
        pack_format = self._get_pack_format()

        if pack_format >= 46:
            item_definition_dir = self.pack_dir / "assets" / "minecraft" / "items"
            item_definition_dir.mkdir(parents=True, exist_ok=True)
            item_definition_file = item_definition_dir / f"{base}.json"
            model = self._read_json(item_definition_file)
            model = model if isinstance(model, dict) else {}

            dispatch = model.get("model")
            is_our_dispatch = (
                isinstance(dispatch, dict)
                and dispatch.get("type") == "minecraft:range_dispatch"
                and dispatch.get("property") == "minecraft:custom_model_data"
            )
            if is_our_dispatch:
                entries = dispatch.get("entries", [])
                entries = entries if isinstance(entries, list) else []
                fallback = dispatch.get("fallback") or self._plain_model(f"minecraft:item/{base}")
            else:
                # Preserve a pre-existing item definition as the fallback when
                # layering generated CMD entries onto an existing resource pack.
                entries = []
                fallback = dispatch if isinstance(dispatch, dict) else self._plain_model(f"minecraft:item/{base}")

            entries = [entry for entry in entries if not (
                isinstance(entry, dict) and self._as_float(entry.get("threshold")) == float(custom_model_data)
            )]
            entries.append({
                "threshold": float(custom_model_data),
                "model": self._plain_model(target_model),
            })
            entries.sort(key=lambda entry: self._as_float(entry.get("threshold")))
            model["model"] = {
                "type": "minecraft:range_dispatch",
                "property": "minecraft:custom_model_data",
                "index": 0,
                "scale": 1.0,
                "entries": entries,
                "fallback": fallback,
            }
            item_definition_file.write_text(json.dumps(model, indent=2), encoding="utf-8")
            return item_definition_file

        vanilla_model_dir = self.pack_dir / "assets" / "minecraft" / "models" / "item"
        vanilla_model_dir.mkdir(parents=True, exist_ok=True)
        base_model_file = vanilla_model_dir / f"{base}.json"

        # Determine parent template (weapons/tools are handheld, items are generated)
        handheld_keywords = ("sword", "axe", "pickaxe", "shovel", "hoe", "wand", "staff", "rod")
        is_handheld = any(kw in base for kw in handheld_keywords)
        parent_type = "minecraft:item/handheld" if is_handheld else "minecraft:item/generated"

        if base_model_file.exists():
            data = self._read_json(base_model_file)
            data = data if isinstance(data, dict) else {}
        else:
            data = {}

        if "parent" not in data:
            data["parent"] = parent_type
        if "textures" not in data:
            data["textures"] = {"layer0": f"minecraft:item/{base}"}
        if "overrides" not in data or not isinstance(data["overrides"], list):
            data["overrides"] = []

        # Remove existing override for this custom_model_data if updating
        overrides = [
            ov for ov in data["overrides"]
            if ov.get("predicate", {}).get("custom_model_data") != custom_model_data
        ]

        # Add new override
        overrides.append({
            "predicate": {
                "custom_model_data": int(custom_model_data)
            },
            "model": target_model
        })

        # Minecraft strictly requires overrides to be sorted ascending by custom_model_data
        overrides.sort(key=lambda x: x.get("predicate", {}).get("custom_model_data", 0))
        data["overrides"] = overrides

        base_model_file.write_text(json.dumps(data, indent=2), encoding="utf-8")
        return base_model_file

    def _get_pack_format(self) -> int:
        """Read the format written by init_pack; default to the legacy default."""
        metadata = self._read_json(self.pack_dir / "pack.mcmeta")
        pack = metadata.get("pack", {}) if isinstance(metadata, dict) else {}
        if isinstance(pack, dict):
            try:
                if "pack_format" in pack:
                    return int(pack["pack_format"])
                min_format = pack.get("min_format")
                if isinstance(min_format, list) and min_format:
                    return int(min_format[0])
            except (TypeError, ValueError):
                pass
        return DEFAULT_PACK_FORMAT

    @staticmethod
    def _read_json(path: pathlib.Path) -> Any:
        try:
            return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
        except (OSError, json.JSONDecodeError):
            return {}

    @staticmethod
    def _plain_model(model_id: str) -> Dict[str, str]:
        return {"type": "minecraft:model", "model": model_id}

    @staticmethod
    def _as_float(value: Any) -> float:
        try:
            return float(value)
        except (TypeError, ValueError):
            return float("-inf")

    def add_custom_item(
        self,
        namespace: str,
        item_id: str,
        image: Image.Image,
        base_vanilla_item: Optional[str] = None,
        custom_model_data: Optional[int] = None,
        display_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """All-in-one helper to register texture, model JSON, and optional CustomModelData override.

        Also generates Java Spigot/Paper code snippet for the plugin generator.
        """
        ns = sanitize_id(namespace)
        item = sanitize_id(item_id)
        
        is_handheld = False
        if base_vanilla_item:
            base_clean = sanitize_id(base_vanilla_item)
            is_handheld = any(kw in base_clean for kw in ("sword", "axe", "pickaxe", "shovel", "hoe", "wand", "staff", "rod"))

        # 1. Save 16x16 PNG
        tex_path = self.save_texture(ns, item, image)

        # 2. Save Item Model JSON
        model_path = self.create_item_model(ns, item, is_handheld=is_handheld)
        target_model_key = f"{ns}:item/{item}"

        # 3. CustomModelData Override (if specified)
        override_path = None
        java_snippet = None

        if base_vanilla_item and custom_model_data is not None and int(custom_model_data) > 0:
            cmd = int(custom_model_data)
            base_clean = sanitize_id(base_vanilla_item)
            override_path = self.register_custom_model_data(
                base_item=base_clean,
                custom_model_data=cmd,
                target_model=target_model_key,
            )
            # Generate ready-to-paste Java Spigot/Paper code snippet for plugin agents
            disp = display_name or item.replace("_", " ").title()
            mat = base_clean.upper()
            java_snippet = (
                f"ItemStack item = new ItemStack(Material.{mat});\n"
                f"ItemMeta meta = item.getItemMeta();\n"
                f"if (meta != null) {{\n"
                f'    meta.setDisplayName("§6{disp}");\n'
                f"    meta.setCustomModelData({cmd});\n"
                f"    item.setItemMeta(meta);\n"
                f"}}"
            )

        return {
            "namespace": ns,
            "item_id": item,
            "resource_location": f"{ns}:{item}",
            "texture_file": str(tex_path),
            "model_file": str(model_path),
            "base_vanilla_item": base_vanilla_item,
            "custom_model_data": custom_model_data,
            "vanilla_override_file": str(override_path) if override_path else None,
            "java_code_snippet": java_snippet,
        }
