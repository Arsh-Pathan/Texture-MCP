"""FastAPI Native REST API Server for Texture-Craft."""

import time
from typing import List, Optional, Dict, Any
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from texture_craft.engine import TextureEngine
from texture_craft.resourcepack import ResourcePackManager

app = FastAPI(
    title="Texture-Craft API",
    description="Native REST API for generating 16x16 Minecraft item textures and resource packs for AI plugin generators.",
    version="2.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ----------------- Request / Response Models -----------------

class HealthResponse(BaseModel):
    status: str
    device: str
    cuda_available: bool
    gpu_name: Optional[str] = None
    vram_total_gb: Optional[float] = None
    vram_allocated_gb: Optional[float] = None
    model_path: str


class GenerateTextureRequest(BaseModel):
    prompt: str = Field(..., description="Item prompt, e.g. 'ruby broadsword', 'frost potion'")
    negative_prompt: str = Field("", description="Negative prompt (leave empty for best results)")
    variants: int = Field(1, ge=1, le=8, description="Number of variants to generate (1-8)")
    seed: Optional[int] = Field(None, description="Random seed (-1 or null for random)")
    steps: int = Field(30, ge=10, le=50, description="DPM-Solver diffusion steps")
    guidance_scale: float = Field(9.0, ge=3.0, le=15.0, description="Classifier-free guidance scale")


class TextureVariant(BaseModel):
    variant_index: int
    seed: int
    latency_sec: float
    base64_png: str
    data_uri: str


class GenerateTextureResponse(BaseModel):
    prompt: str
    count: int
    results: List[TextureVariant]


class InitResourcePackRequest(BaseModel):
    pack_dir: str = Field(..., description="Root path on disk for resource pack")
    pack_name: str = Field("PluginPack", description="Name of the resource pack")
    description: str = Field("Generated by Texture-Craft", description="Pack description in pack.mcmeta")
    pack_format: int = Field(34, description="Minecraft pack_format (34 = 1.21/1.21.1)")


class ResourcePackItemRequest(BaseModel):
    pack_dir: str = Field(..., description="Root path of the resource pack")
    namespace: str = Field("custom", description="Resourcepack namespace (e.g. 'myplugin')")
    item_id: str = Field(..., description="Item ID, e.g. 'frost_sword', 'mana_potion'")
    prompt: str = Field(..., description="Texture generation prompt")
    seed: Optional[int] = Field(None, description="Seed for reproducibility")
    steps: int = Field(30, ge=10, le=50)
    guidance_scale: float = Field(9.0, ge=3.0, le=15.0)
    base_vanilla_item: Optional[str] = Field(None, description="Vanilla item for CustomModelData, e.g. 'diamond_sword'")
    custom_model_data: Optional[int] = Field(None, description="CustomModelData integer identifier, e.g. 1001")
    display_name: Optional[str] = Field(None, description="In-game display name for Java code snippet")


class ResourcePackItemResponse(BaseModel):
    namespace: str
    item_id: str
    resource_location: str
    texture_file: str
    model_file: str
    base_vanilla_item: Optional[str] = None
    custom_model_data: Optional[int] = None
    vanilla_override_file: Optional[str] = None
    base64_preview: str
    seed: int
    latency_sec: float
    java_code_snippet: Optional[str] = None


class BatchPackItem(BaseModel):
    item_id: str
    prompt: str
    seed: Optional[int] = None
    base_vanilla_item: Optional[str] = None
    custom_model_data: Optional[int] = None
    display_name: Optional[str] = None


class BatchResourcePackRequest(BaseModel):
    pack_dir: str
    namespace: str = "custom"
    init_pack_if_missing: bool = True
    pack_name: str = "PluginResourcePack"
    items: List[BatchPackItem]


class BatchResourcePackResponse(BaseModel):
    pack_dir: str
    total_items: int
    total_latency_sec: float
    items: List[ResourcePackItemResponse]


# ----------------- API Endpoints -----------------

@app.get("/health", response_model=HealthResponse)
def health():
    """System health check and GPU telemetry."""
    engine = TextureEngine.get_instance()
    return engine.get_system_status()


@app.post("/v1/textures/generate", response_model=GenerateTextureResponse)
def generate_textures(req: GenerateTextureRequest):
    """Generates 16x16 transparent PNG textures as base64."""
    engine = TextureEngine.get_instance()
    variants = engine.generate_batch(
        prompt=req.prompt,
        variants=req.variants,
        negative_prompt=req.negative_prompt,
        seed_base=req.seed,
        steps=req.steps,
        guidance_scale=req.guidance_scale,
    )

    results = [
        TextureVariant(
            variant_index=v["variant_index"],
            seed=v["seed"],
            latency_sec=v["latency_sec"],
            base64_png=v["base64_tile"],
            data_uri=v["data_uri_tile"],
        )
        for v in variants
    ]
    return GenerateTextureResponse(prompt=req.prompt, count=len(results), results=results)


@app.post("/v1/resourcepack/init")
def init_resource_pack(req: InitResourcePackRequest):
    """Initializes resource pack directory with pack.mcmeta."""
    manager = ResourcePackManager(req.pack_dir)
    return manager.init_pack(
        pack_name=req.pack_name,
        description=req.description,
        pack_format=req.pack_format,
    )


@app.post("/v1/resourcepack/item", response_model=ResourcePackItemResponse)
def add_item_to_resource_pack(req: ResourcePackItemRequest):
    """Generates a texture and integrates it into a resource pack with model JSON and CustomModelData."""
    engine = TextureEngine.get_instance()
    manager = ResourcePackManager(req.pack_dir)

    tile, _, seed, latency = engine.generate_single(
        prompt=req.prompt,
        seed=req.seed,
        steps=req.steps,
        guidance_scale=req.guidance_scale,
    )

    item_meta = manager.add_custom_item(
        namespace=req.namespace,
        item_id=req.item_id,
        image=tile,
        base_vanilla_item=req.base_vanilla_item,
        custom_model_data=req.custom_model_data,
        display_name=req.display_name,
    )

    return ResourcePackItemResponse(
        namespace=item_meta["namespace"],
        item_id=item_meta["item_id"],
        resource_location=item_meta["resource_location"],
        texture_file=item_meta["texture_file"],
        model_file=item_meta["model_file"],
        base_vanilla_item=item_meta["base_vanilla_item"],
        custom_model_data=item_meta["custom_model_data"],
        vanilla_override_file=item_meta["vanilla_override_file"],
        base64_preview=engine.image_to_base64(tile),
        seed=seed,
        latency_sec=latency,
        java_code_snippet=item_meta["java_code_snippet"],
    )


@app.post("/v1/resourcepack/batch", response_model=BatchResourcePackResponse)
def batch_create_resource_pack_items(req: BatchResourcePackRequest):
    """Batches multiple item textures, models, and CustomModelData registrations in a single call."""
    t_start = time.time()
    engine = TextureEngine.get_instance()
    manager = ResourcePackManager(req.pack_dir)

    if req.init_pack_if_missing:
        mcmeta = manager.pack_dir / "pack.mcmeta"
        if not mcmeta.exists():
            manager.init_pack(pack_name=req.pack_name)

    created_items = []
    for item in req.items:
        tile, _, seed, latency = engine.generate_single(
            prompt=item.prompt,
            seed=item.seed,
        )
        meta = manager.add_custom_item(
            namespace=req.namespace,
            item_id=item.item_id,
            image=tile,
            base_vanilla_item=item.base_vanilla_item,
            custom_model_data=item.custom_model_data,
            display_name=item.display_name,
        )
        created_items.append(
            ResourcePackItemResponse(
                namespace=meta["namespace"],
                item_id=meta["item_id"],
                resource_location=meta["resource_location"],
                texture_file=meta["texture_file"],
                model_file=meta["model_file"],
                base_vanilla_item=meta["base_vanilla_item"],
                custom_model_data=meta["custom_model_data"],
                vanilla_override_file=meta["vanilla_override_file"],
                base64_preview=engine.image_to_base64(tile),
                seed=seed,
                latency_sec=latency,
                java_code_snippet=meta["java_code_snippet"],
            )
        )

    total_latency = round(time.time() - t_start, 2)
    return BatchResourcePackResponse(
        pack_dir=req.pack_dir,
        total_items=len(created_items),
        total_latency_sec=total_latency,
        items=created_items,
    )


def main():
    import uvicorn
    # Pre-warm model on startup
    TextureEngine.get_instance()
    uvicorn.run("server:app", host="0.0.0.0", port=8000, reload=False)


if __name__ == "__main__":
    main()
