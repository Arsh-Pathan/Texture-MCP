"""Model Context Protocol (MCP) Server for Texture-Craft.

Exposes tools for AI agents (Cursor, Claude Desktop, Antigravity, Custom Agents)
to generate Minecraft 16x16 textures, build resource packs, and manage CustomModelData.
"""

import argparse
import json
import sys
from typing import Dict, Any, Optional

from mcp.server.mcpserver import MCPServer
from texture_craft.engine import TextureEngine
from texture_craft.resourcepack import ResourcePackManager

# Initialize MCP Server
app = MCPServer("TextureCraft")


@app.tool()
def generate_texture(
    prompt: str,
    variants: int = 1,
    seed: int = -1,
    steps: int = 30,
    guidance_scale: float = 9.0,
) -> Dict[str, Any]:
    """Generates 16x16 transparent Minecraft item textures from a text prompt.

    Args:
        prompt: Item description, e.g. 'ruby broadsword', 'frost potion', 'void crystal', 'golden wand'.
        variants: Number of variations to generate (1 to 4).
        seed: Random seed for reproducibility (-1 for random).
        steps: Diffusion inference steps (default 30).
        guidance_scale: Guidance scale (default 9.0).

    Returns:
        Dictionary containing prompt, variant results with base64 PNGs and seeds.
    """
    engine = TextureEngine.get_instance()
    results = engine.generate_batch(
        prompt=prompt,
        variants=max(1, min(variants, 4)),
        seed_base=seed if seed >= 0 else None,
        steps=steps,
        guidance_scale=guidance_scale,
    )
    return {
        "prompt": prompt,
        "count": len(results),
        "variants": [
            {
                "variant_index": r["variant_index"],
                "seed": r["seed"],
                "latency_sec": r["latency_sec"],
                "base64_png": r["base64_tile"],
                "data_uri": r["data_uri_tile"],
            }
            for r in results
        ],
    }


@app.tool()
def create_resourcepack_item(
    pack_dir: str,
    item_id: str,
    prompt: str,
    namespace: str = "custom",
    base_vanilla_item: str = "",
    custom_model_data: int = -1,
    display_name: str = "",
    seed: int = -1,
) -> Dict[str, Any]:
    """Generates an item texture and integrates it into a Minecraft resource pack.

    Creates:
    - assets/<namespace>/textures/item/<item_id>.png (16x16 RGBA with transparency)
    - assets/<namespace>/models/item/<item_id>.json (item model)
    - assets/minecraft/models/item/<base_item>.json (CustomModelData override, sorted)

    Args:
        pack_dir: Root directory of the Minecraft resource pack.
        item_id: Unique identifier for the item (e.g. 'frost_sword', 'mana_potion').
        prompt: Description of item for the texture generator (e.g. 'glowing frost sword with blue runes').
        namespace: Custom namespace (default: 'custom' or plugin name).
        base_vanilla_item: Vanilla item to override, e.g. 'diamond_sword', 'stick', 'potion'.
        custom_model_data: Integer ID for CustomModelData (e.g. 1001).
        display_name: In-game name for Java Spigot snippet (e.g. 'Frost Sword').
        seed: Seed for reproducibility (-1 for random).

    Returns:
        Created file paths, base64 preview, and ready-to-use Java Spigot code snippet.
    """
    engine = TextureEngine.get_instance()
    manager = ResourcePackManager(pack_dir)

    tile, _, used_seed, latency = engine.generate_single(
        prompt=prompt,
        seed=seed if seed >= 0 else None,
    )

    cmd = custom_model_data if custom_model_data > 0 else None
    base_item = base_vanilla_item if base_vanilla_item.strip() else None

    meta = manager.add_custom_item(
        namespace=namespace,
        item_id=item_id,
        image=tile,
        base_vanilla_item=base_item,
        custom_model_data=cmd,
        display_name=display_name or None,
    )

    return {
        "status": "success",
        "namespace": meta["namespace"],
        "item_id": meta["item_id"],
        "resource_location": meta["resource_location"],
        "texture_file": meta["texture_file"],
        "model_file": meta["model_file"],
        "vanilla_override_file": meta["vanilla_override_file"],
        "base64_preview": engine.image_to_base64(tile),
        "seed": used_seed,
        "latency_sec": latency,
        "java_code_snippet": meta["java_code_snippet"],
    }


@app.tool()
def init_resourcepack(
    pack_dir: str,
    pack_name: str = "PluginResourcePack",
    description: str = "Custom Resource Pack generated by Texture-Craft",
    pack_format: int = 34,
) -> Dict[str, Any]:
    """Initializes a new Minecraft resource pack with pack.mcmeta and standard directory structure.

    Args:
        pack_dir: Directory where the resource pack should be created.
        pack_name: Human-readable name for the pack.
        description: Description written in pack.mcmeta.
        pack_format: Minecraft format version (34 = 1.21/1.21.1, 42 = 1.21.2+, 46 = 1.21.4).
    """
    manager = ResourcePackManager(pack_dir)
    return manager.init_pack(
        pack_name=pack_name,
        description=description,
        pack_format=pack_format,
    )


@app.tool()
def batch_create_resourcepack_items(
    pack_dir: str,
    namespace: str,
    items_json: str,
) -> Dict[str, Any]:
    """Batches multiple item textures and CustomModelData mappings into a resource pack at once.

    Args:
        pack_dir: Root directory of resource pack.
        namespace: Resource pack namespace.
        items_json: JSON string representing list of item dicts:
            [
              {"item_id": "flame_sword", "prompt": "flaming sword", "base_vanilla_item": "diamond_sword", "custom_model_data": 1001, "display_name": "Flame Sword"},
              {"item_id": "mana_potion", "prompt": "blue mana potion", "base_vanilla_item": "potion", "custom_model_data": 2001, "display_name": "Mana Potion"}
            ]
    """
    try:
        items = json.loads(items_json)
    except Exception as e:
        return {"status": "error", "message": f"Invalid JSON format: {str(e)}"}

    engine = TextureEngine.get_instance()
    manager = ResourcePackManager(pack_dir)

    created = []
    for item in items:
        item_id = item.get("item_id", "item")
        prompt = item.get("prompt", item_id)
        seed = item.get("seed", -1)
        base_item = item.get("base_vanilla_item")
        cmd = item.get("custom_model_data")
        disp = item.get("display_name")

        tile, _, s, lat = engine.generate_single(
            prompt=prompt,
            seed=seed if seed >= 0 else None,
        )

        meta = manager.add_custom_item(
            namespace=namespace,
            item_id=item_id,
            image=tile,
            base_vanilla_item=base_item,
            custom_model_data=cmd,
            display_name=disp,
        )
        created.append({
            "item_id": item_id,
            "resource_location": meta["resource_location"],
            "texture_file": meta["texture_file"],
            "model_file": meta["model_file"],
            "custom_model_data": cmd,
            "java_code_snippet": meta["java_code_snippet"],
        })

    return {
        "status": "success",
        "pack_dir": pack_dir,
        "total_created": len(created),
        "items": created,
    }


@app.tool()
def get_system_status() -> Dict[str, Any]:
    """Returns GPU acceleration, VRAM usage, and engine status."""
    engine = TextureEngine.get_instance()
    return engine.get_system_status()


def main():
    parser = argparse.ArgumentParser(description="Texture-Craft MCP Server")
    parser.add_argument("--transport", choices=["stdio", "sse", "streamable-http"], default="stdio")
    parser.add_argument("--port", type=int, default=8001)
    args = parser.parse_args()

    # Preload engine before listening so first agent call is instant
    print("[MCP] Warming up TextureEngine...", file=sys.stderr)
    TextureEngine.get_instance()
    print(f"[MCP] Starting server with {args.transport} transport...", file=sys.stderr)

    if args.transport == "stdio":
        app.run(transport="stdio")
    else:
        app.run(transport=args.transport, port=args.port)


if __name__ == "__main__":
    main()
